def generate_excel(report_type: str, data: dict, generated_by: str, filters: dict) -> bytes:
    from openpyxl import Workbook
    from openpyxl.styles import Font, PatternFill, Alignment, Border, Side
    from openpyxl.utils import get_column_letter

    wb = Workbook()

    GOLD = "F59E0B"
    DARK = "0F172A"
    MID = "1E293B"
    WHITE = "FFFFFF"
    RED = "EF4444"
    GREEN = "10B981"

    def hdr_font():
        return Font(bold=True, color=WHITE, size=9)

    def hdr_fill():
        return PatternFill("solid", fgColor=DARK)

    def gold_font():
        return Font(bold=True, color=GOLD, size=10)

    def thin_border():
        s = Side(style="thin", color="334155")
        return Border(left=s, right=s, top=s, bottom=s)

    def write_sheet(ws, title, headers, rows):
        ws.title = title
        ws.sheet_properties.tabColor = GOLD
        # Title row
        ws.append([f"HoneyPrompt Sentinel — {title}"])
        ws.append([f"Generated by: {generated_by}  |  {datetime.now().strftime('%Y-%m-%d %H:%M:%S')}"])
        ws.append([])
        # Headers
        ws.append(headers)
        for col_idx, _ in enumerate(headers, 1):
            cell = ws.cell(row=4, column=col_idx)
            cell.font = hdr_font()
            cell.fill = hdr_fill()
            cell.alignment = Alignment(horizontal="center")
            cell.border = thin_border()
        # Data
        for row in rows:
            ws.append([str(v) if v is not None else "" for v in row])
        # Column widths
        for col_idx in range(1, len(headers) + 1):
            col_letter = get_column_letter(col_idx)
            max_len = max(
                (len(str(ws.cell(row=r, column=col_idx).value or "")) for r in range(4, ws.max_row + 1)),
                default=10
            )
            ws.column_dimensions[col_letter].width = min(max(max_len + 2, 12), 45)
        # Title styling
        ws["A1"].font = gold_font()
        ws["A2"].font = Font(color="94A3B8", size=8)

    # ---- Summary sheet ----
    ws_sum = wb.active
    summary_rows = []

    if report_type in ("security_overview", "personal_security"):
        s = data.get("summary", {})
        for k, v in s.items():
            summary_rows.append([k.replace("_", " ").title(), _fmt(v)])
        write_sheet(ws_sum, "Summary", ["Metric", "Value"], summary_rows)
    else:
        write_sheet(ws_sum, "Summary", ["Report", "Generated At", "Generated By"],
                    [[report_type, datetime.now().isoformat(), generated_by]])

    # ---- Type-specific sheets ----
    if report_type == "security_overview":
        # Users sheet
        ws_u = wb.create_sheet("Users")
        users = data.get("users", [])
        write_sheet(ws_u, "Users", ["Username", "Email", "Status", "Total", "Safe", "Suspicious", "Malicious", "Blocked", "Risk Score"],
            [[r.get("username"), r.get("email"), r.get("status"), r.get("total_prompts"),
              r.get("safe"), r.get("suspicious"), r.get("malicious"), r.get("blocked"), r.get("risk_score")]
             for r in users])

        # Threats sheet
        ws_t = wb.create_sheet("Threats")
        write_sheet(ws_t, "Threats", ["Threat Type", "Count"],
            [[k, v] for k, v in (data.get("threat_by_type") or {}).items()])

        # Severity sheet
        ws_s = wb.create_sheet("Severity")
        write_sheet(ws_s, "Severity", ["Severity", "Count"],
            [[k, v] for k, v in (data.get("severity_dist") or {}).items()])

    elif report_type == "threat_intelligence":
        ws_t = wb.create_sheet("Threats")
        write_sheet(ws_t, "Threats",
            ["Threat Type", "Count", "Severity", "Avg Confidence"],
            [[r.get("threat_type"), r.get("count"), r.get("severity"), _pct(r.get("avg_confidence"))]
             for r in data.get("threats", [])])

        ws_u = wb.create_sheet("Top Users")
        write_sheet(ws_u, "Top Users", ["Username", "Attack Count"],
            [[u, c] for u, c in (data.get("top_users") or {}).items()])

    elif report_type == "user_security":
        ws_u = wb.create_sheet("Users")
        write_sheet(ws_u, "Users",
            ["Username", "Email", "Status", "Total", "Safe", "Suspicious", "Malicious", "Blocked", "Risk Score", "Last Activity"],
            [[r.get("username"), r.get("email"), r.get("status"), r.get("total_prompts"),
              r.get("safe"), r.get("suspicious"), r.get("malicious"), r.get("blocked"),
              r.get("risk_score"), _date(r.get("last_activity"))]
             for r in data.get("users", [])])

    elif report_type == "audit_log":
        ws_a = wb.create_sheet("Audit Logs")
        write_sheet(ws_a, "Audit Logs",
            ["Timestamp", "Admin", "Action", "Target", "Reason"],
            [[_date(r.get("timestamp")), r.get("admin"), r.get("action"),
              r.get("target"), r.get("reason")]
             for r in data.get("logs", [])])

    elif report_type == "incidents":
        ws_i = wb.create_sheet("Incidents")
        write_sheet(ws_i, "Incidents",
            ["Incident ID", "Created", "Title", "Severity", "Status", "Admin", "Resolved At"],
            [[r.get("incident_id"), _date(r.get("created_at")), r.get("title"),
              r.get("severity"), r.get("status"), r.get("created_by"), _date(r.get("resolved_at"))]
             for r in data.get("incidents", [])])

    elif report_type == "chat_activity":
        ws_c = wb.create_sheet("Activity")
        s = data.get("summary", {})
        write_sheet(ws_c, "Activity", ["Metric", "Value"],
            [[k.replace("_", " ").title(), v] for k, v in s.items()])

    elif report_type == "personal_security":
        ws_h = wb.create_sheet("Security History")
        write_sheet(ws_h, "Security History",
            ["Timestamp", "Prompt Preview", "Classification", "Threat Type", "Severity", "Confidence", "Action"],
            [[_date(r.get("timestamp")), r.get("prompt_preview"), r.get("classification"),
              r.get("threat_type"), r.get("severity"), _pct(r.get("confidence")), r.get("action")]
             for r in data.get("history", [])])

    elif report_type == "security_history":
        ws_h = wb.create_sheet("Security History")
        write_sheet(ws_h, "Security History",
            ["Timestamp", "Prompt Preview", "Classification", "Threat Type", "Severity", "Confidence", "Action", "Reason"],
            [[_date(r.get("timestamp")), r.get("prompt_preview"), r.get("classification"),
              r.get("threat_type"), r.get("severity"), _pct(r.get("confidence")),
              r.get("action"), r.get("reason")]
             for r in data.get("history", [])])

    elif report_type == "my_chat_activity":
        ws_c = wb.create_sheet("Chat Activity")
        s = data.get("summary", {})
        write_sheet(ws_c, "Chat Activity", ["Metric", "Value"],
            [[k.replace("_", " ").title(), v] for k, v in s.items()])

    elif report_type == "security_alerts":
        ws_a = wb.create_sheet("Alerts")
        write_sheet(ws_a, "Alerts",
            ["Timestamp", "Threat Type", "Severity", "Classification", "Action", "Reason"],
            [[_date(r.get("timestamp")), r.get("threat_type"), r.get("severity"),
              r.get("classification"), r.get("action"), r.get("reason")]
             for r in data.get("alerts", [])])

    buf = io.BytesIO()
    wb.save(buf)
    return buf.getvalue()
